---Look up help for a dotted or bare name.
---Tries std. prefix and short twin automatically.
---@param word string e.g. "http.get" or "get"
---@return table|nil {sig, doc}
function M.get(word)
  if M.docs[word] then
    return M.docs[word]
  end
  if M.docs["std." .. word] then
    return M.docs["std." .. word]
  end
  -- bare stdlib function: search short twins ("get" -> "http.get" ambiguous,
  -- so only match when the suffix is unique)
  local hit = nil
  for name, entry in pairs(M.docs) do
    if not name:find(".", 1, true) and name == word then
      return entry
    end
    local short = name:match("%.([^.]+)$")
    if short == word then
      if hit then
        return nil -- ambiguous, stay quiet
      end
      hit = entry
    end
  end
  return hit
end

---Show help for the word under the cursor in a floating window.
function M.show_cursor()
  local word = vim.fn.expand("<cword>")
  -- include dotted receiver: grab `module.word` when present
  local line = vim.api.nvim_get_current_line()
  local col = vim.api.nvim_win_get_cursor(0)[2] + 1
  local dotted = line:sub(1, col):match("([A-Za-z_][A-Za-z0-9_]*%.[A-Za-z_][A-Za-z0-9_]*)$")
  local entry = M.get(dotted or word)
  if not entry then
    vim.notify("zz-lang: no docs for `" .. (dotted or word) .. "`", vim.log.levels.INFO)
    return
  end
  local lines = vim.split(entry.sig, "\n", { plain = true })
  if entry.doc ~= "" then
    vim.list_extend(lines, { "", entry.doc })
  end
  vim.lsp.util.open_floating_preview(lines, "markdown", {
    border = "rounded",
    focusable = false,
  })
end

return M
